# -*- coding: utf-8 -*-
"""Verify price-alert.html against all user requirements."""
p = "/Users/btm6/jokerai/price-alert.html"
s = open(p, encoding="utf-8").read()

def ok(name, cond):
    print("  [%s] %s" % ("OK" if cond else "MISSING", name))

print("=== price-alert.html verification ===")
ok("DOCTYPE html", s.lstrip().startswith("<!DOCTYPE html>"))
ok("ends </html>", s.rstrip().endswith("</html>"))
ok("lang=en", '<html lang="en">' in s)
ok("links report-style.css", '<link rel="stylesheet" href="report-style.css">' in s)
ok("mobile max-width 720", "@media (max-width: 720px)" in s)
ok("date YYYY-MM-DD", "2026-11-07" in s)
ok("update time SGT", "2026-11-07 15:02 SGT" in s)
ok("15-min delayed", "15-min delayed" in s)
ok("Moomoo OpenD", "Moomoo OpenD" in s)
for sec in ["📋 Executive Summary", "🔥 Watchlist Movers", "🚨 Portfolio Alerts",
            "▶️ YouTube Hot Videos", "🇺🇸 USA Branded News", "📊 Sector &amp; Risk", "📈 Signal Summary"]:
    ok(sec, sec in s)
for pat in ["None", "数据获取失败", "{{", "}}", "f\"", "f'"]:
    n = s.count(pat)
    if n:
        ok("absence " + repr(pat), n == 0)
for needle in ["89.68", "449.04", "16.71", "328.53", "293.69", "239.30", "170.80", "141.20",
               "+9.75%", "+13.21%", "+11.04%", "+5.73%", "+3.67%", "+7.31%", "+0.74%", "-2.90%",
               "🟢", "🔴", "HOLD / REVIEW", "2026-11-07 15:02:28 SGT", "Generated by Hermes Agent"]:
    ok("contains " + repr(needle), needle in s)
for chip in ["schwab", "investopedia", "yahoo"]:
    ok("source-chip " + chip, ('class="source-chip ' + chip + '"') in s)
print("  [INFO] total chars:", len(s))
